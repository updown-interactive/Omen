//! Reusable state, environment and localization declarations.
use proc_macro2::TokenStream;
use quote::quote;
use syn::{
    Token, braced,
    parse::{Parse, ParseStream},
};

struct Field {
    attributes: Vec<syn::Attribute>,
    name: syn::Ident,
    ty: syn::Type,
    value: Option<syn::Expr>,
    visibility: syn::Visibility,
    reactive: bool,
}
struct Model {
    attributes: Vec<syn::Attribute>,
    visibility: syn::Visibility,
    name: syn::Ident,
    fields: Vec<Field>,
    methods: Vec<syn::ImplItemFn>,
}
fn inferred_type(value: &syn::Expr) -> Option<syn::Type> {
    match value {
        syn::Expr::Lit(lit) => match &lit.lit {
            syn::Lit::Str(_) => Some(syn::parse_quote!(::std::string::String)),
            syn::Lit::Bool(_) => Some(syn::parse_quote!(bool)),
            syn::Lit::Char(_) => Some(syn::parse_quote!(char)),
            syn::Lit::Int(number) => syn::parse_str(if number.suffix().is_empty() {
                "i32"
            } else {
                number.suffix()
            })
            .ok(),
            syn::Lit::Float(number) => syn::parse_str(if number.suffix().is_empty() {
                "f64"
            } else {
                number.suffix()
            })
            .ok(),
            _ => None,
        },
        syn::Expr::Unary(unary) => inferred_type(&unary.expr),
        _ => None,
    }
}
impl Parse for Model {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let attributes = input.call(syn::Attribute::parse_outer)?;
        let visibility = input.parse()?;
        let name = input.parse()?;
        let body;
        braced!(body in input);
        let mut fields = Vec::new();
        let mut methods = Vec::new();
        let mut names = std::collections::HashSet::new();
        let mut method_names = std::collections::HashSet::new();
        while !body.is_empty() {
            let attributes = body.call(syn::Attribute::parse_outer)?;
            let ahead = body.fork();
            let _: syn::Visibility = ahead.parse()?;
            if ahead.peek(Token![fn])
                || ahead.peek(Token![async])
                || ahead.peek(Token![const])
                || ahead.peek(Token![unsafe])
            {
                let mut method: syn::ImplItemFn = body.parse().map_err(|error| {
                    syn::Error::new(
                        error.span(),
                        format!("expected a state field or Rust method: {error}"),
                    )
                })?;
                if matches!(method.sig.ident.to_string().as_str(), "new" | "shared") {
                    return Err(syn::Error::new_spanned(
                        &method.sig.ident,
                        "this method is generated by state!; choose another method name",
                    ));
                }
                if !method_names.insert(method.sig.ident.to_string()) {
                    return Err(syn::Error::new_spanned(
                        &method.sig.ident,
                        "duplicate state method",
                    ));
                }
                method.attrs.splice(0..0, attributes);
                methods.push(method);
                continue;
            }
            let mut reactive = false;
            if body.peek(Token![@]) {
                body.parse::<Token![@]>()?;
                let marker: syn::Ident = body.parse()?;
                reactive = marker == "Reactive";
                if marker != "State" && marker != "Environment" && !reactive {
                    return Err(syn::Error::new_spanned(
                        marker,
                        "expected let, @State let, @Environment let or @Reactive",
                    ));
                }
            }
            if body.peek(Token![let]) {
                body.parse::<Token![let]>()?;
            }
            let visibility: syn::Visibility = body.parse()?;
            let visibility = if matches!(visibility, syn::Visibility::Inherited) {
                syn::parse_quote!(pub)
            } else {
                visibility
            };
            let name: syn::Ident = body.parse()?;
            if !names.insert(name.to_string()) {
                return Err(syn::Error::new_spanned(name, "duplicate model field"));
            }
            let ty: Option<syn::Type> = if body.peek(Token![:]) {
                body.parse::<Token![:]>()?;
                Some(body.parse()?)
            } else {
                None
            };
            let mut value: Option<syn::Expr> = if body.peek(Token![=]) {
                body.parse::<Token![=]>()?;
                Some(body.parse()?)
            } else {
                None
            };
            let ty = ty
                .or_else(|| value.as_ref().and_then(inferred_type))
                .ok_or_else(|| {
                    syn::Error::new_spanned(
                        &name,
                        "cannot infer this state field; specify a type: name: Type = value",
                    )
                })?;
            if let Some(expression) = &mut value
                && matches!(expression,syn::Expr::Lit(lit) if matches!(lit.lit,syn::Lit::Str(_)))
            {
                *expression = syn::parse_quote!(::core::convert::Into::into(#expression));
            }
            if body.peek(Token![;]) {
                body.parse::<Token![;]>()?;
            }
            if body.peek(Token![,]) {
                body.parse::<Token![,]>()?;
            }
            fields.push(Field {
                attributes,
                name,
                ty,
                value,
                visibility,
                reactive,
            });
        }
        Ok(Self {
            attributes,
            visibility,
            name,
            fields,
            methods,
        })
    }
}
pub(crate) fn model(tokens: TokenStream) -> syn::Result<TokenStream> {
    model_impl(tokens, false)
}
pub(crate) fn environment(tokens: TokenStream) -> syn::Result<TokenStream> {
    model_impl(tokens, true)
}
fn model_impl(tokens: TokenStream, environment: bool) -> syn::Result<TokenStream> {
    let Model {
        attributes,
        visibility,
        name,
        fields,
        methods,
    } = syn::parse2(tokens)?;
    if !environment {
        for field in &fields {
            if field.reactive {
                return Err(syn::Error::new_spanned(
                    &field.name,
                    "@Reactive fields belong in environment!; state! already observes its model",
                ));
            }
            if field.value.is_none() {
                return Err(syn::Error::new_spanned(
                    &field.name,
                    "state fields require an initializer: field[: Type] = value",
                ));
            }
        }
    }
    let constructor_parameters = fields
        .iter()
        .filter(|field| field.value.is_none())
        .map(|field| {
            let name = &field.name;
            let ty = &field.ty;
            quote!(#name: #ty)
        })
        .collect::<Vec<_>>();
    let constructor_arguments = fields
        .iter()
        .filter(|field| field.value.is_none())
        .map(|field| &field.name)
        .collect::<Vec<_>>();
    let declarations = fields.iter().map(|field| {
        let Field {
            attributes,
            name,
            ty,
            visibility,
            reactive,
            ..
        } = field;
        let ty = if *reactive {
            quote!(::omen_ui::Value<#ty>)
        } else {
            quote!(#ty)
        };
        quote!(#(#attributes)* #[doc="An Omen model field."] #visibility #name:#ty)
    });
    let initializers = fields.iter().map(|field| {
        let Field {
            attributes,
            name,
            ty,
            value,
            reactive,
            ..
        } = field;
        let attributes = attributes
            .iter()
            .filter(|attr| attr.path().is_ident("cfg") || attr.path().is_ident("cfg_attr"));
        let value = value
            .as_ref()
            .map(|value| quote!(#value))
            .unwrap_or_else(|| quote!(#name));
        if *reactive {
            quote!(#(#attributes)* let #name=::omen_ui::Value::<#ty>::new(#value);)
        } else {
            quote!(#(#attributes)* let #name:#ty=#value;)
        }
    });
    let names = fields.iter().map(|field| {
        let name = &field.name;
        let attributes = field
            .attributes
            .iter()
            .filter(|attr| attr.path().is_ident("cfg") || attr.path().is_ident("cfg_attr"));
        quote!(#(#attributes)* #name)
    });
    let derive_clone = if (environment && fields.iter().any(|field| field.reactive))
        || attributes.iter().any(|attribute| {
            attribute.path().is_ident("derive")
                && attribute
                    .parse_args_with(
                        syn::punctuated::Punctuated::<syn::Path, Token![,]>::parse_terminated,
                    )
                    .is_ok_and(|paths| paths.iter().any(|path| path.is_ident("Clone")))
        }) {
        quote!()
    } else {
        quote!(#[derive(Clone)])
    };
    let conditional_attributes = attributes
        .iter()
        .filter(|attribute| {
            attribute.path().is_ident("cfg") || attribute.path().is_ident("cfg_attr")
        })
        .collect::<Vec<_>>();
    let injection = environment.then(|| {
        quote! {
            #(#conditional_attributes)*
            impl ::omen_ui::EnvironmentSource for #name {
                type Model = Self;
                fn into_environment(self) -> ::omen_ui::Value<Self> { ::omen_ui::Value::new(self) }
            }
        }
    });
    let default_impl = constructor_parameters.is_empty().then(|| {
        quote! {
            #(#conditional_attributes)*
            impl ::core::default::Default for #name {fn default()->Self {Self::new()}}
        }
    });
    Ok(quote! {
        #injection
        #[doc="A reusable Omen state or environment model."]
        #(#attributes)*
        #derive_clone
        #visibility struct #name { #(#declarations),* }
        #(#conditional_attributes)*
        impl #name {
            #[doc="Create this model with its declared initial values."]
            pub fn new(#(#constructor_parameters),*)->Self { #(#initializers)* Self{#(#names),*} }
            #[doc="Create an observable instance suitable for environment injection."]
            pub fn shared(#(#constructor_parameters),*)->::omen_ui::Observable<Self> {::omen_ui::Observable::new(Self::new(#(#constructor_arguments),*))}
            #(#methods)*
        }
        #default_impl
    })
}
struct Catalog {
    visibility: syn::Visibility,
    name: syn::Ident,
    data: CatalogData,
}
struct CatalogData {
    default: String,
    typed: bool,
    entries: std::collections::BTreeMap<String, std::collections::BTreeMap<String, Message>>,
}
#[derive(Clone)]
struct Message {
    variants: Vec<(String, syn::LitStr)>,
    parameters: Vec<syn::Ident>,
    plural: bool,
}
fn parameters(text: &syn::LitStr) -> syn::Result<Vec<syn::Ident>> {
    let value = text.value();
    let mut rest = value.as_str();
    let mut names = std::collections::BTreeSet::new();
    while let Some(start) = rest.find('{') {
        rest = &rest[start + 1..];
        let end = rest
            .find('}')
            .ok_or_else(|| syn::Error::new_spanned(text, "unclosed interpolation parameter"))?;
        let name = &rest[..end];
        syn::parse_str::<syn::Ident>(name).map_err(|_| {
            syn::Error::new_spanned(text, "interpolation parameters must be Rust identifiers")
        })?;
        names.insert(name.to_string());
        rest = &rest[end + 1..];
    }
    names
        .into_iter()
        .map(|name| syn::parse_str(&name))
        .collect()
}
fn catalog_data(input: ParseStream<'_>) -> syn::Result<CatalogData> {
    let mut default = None;
    let mut first = None;
    let mut entries = std::collections::BTreeMap::new();
    while !input.is_empty() {
        if input.peek(Token![default]) {
            input.parse::<Token![default]>()?;
            input.parse::<Token![:]>()?;
            let value: syn::LitStr = input.parse()?;
            if default.replace(value.value()).is_some() {
                return Err(syn::Error::new_spanned(value, "duplicate default locale"));
            }
            if input.peek(Token![,]) {
                input.parse::<Token![,]>()?;
            }
            continue;
        }
        let (locale, span) = if input.peek(syn::LitStr) {
            let locale: syn::LitStr = input.parse()?;
            (locale.value(), locale.span())
        } else {
            let locale: syn::Ident = input.parse()?;
            (locale.to_string(), locale.span())
        };
        if locale
            .replace('_', "-")
            .parse::<unic_langid::LanguageIdentifier>()
            .is_err()
        {
            return Err(syn::Error::new(span, "invalid locale identifier"));
        }
        first.get_or_insert_with(|| locale.clone());
        let body;
        braced!(body in input);
        let mut messages = std::collections::BTreeMap::new();
        while !body.is_empty() {
            let key: syn::Ident = body.parse()?;
            if matches!(
                key.to_string().as_str(),
                "new"
                    | "typed"
                    | "default"
                    | "locale"
                    | "set_locale"
                    | "text"
                    | "format"
                    | "plural"
                    | "try_set_locale"
                    | "supported_locales"
            ) {
                return Err(syn::Error::new_spanned(
                    key,
                    "translation key conflicts with a localization resource method",
                ));
            }
            body.parse::<Token![:]>()?;
            let plural = body.peek(syn::token::Brace);
            let mut variants = Vec::new();
            if plural {
                let forms;
                braced!(forms in body);
                let mut seen = std::collections::HashSet::new();
                while !forms.is_empty() {
                    let form: syn::Ident = forms.parse()?;
                    if !matches!(
                        form.to_string().as_str(),
                        "zero" | "one" | "two" | "few" | "many" | "other"
                    ) || !seen.insert(form.to_string())
                    {
                        return Err(syn::Error::new_spanned(
                            form,
                            "expected a unique plural category: zero, one, two, few, many or other",
                        ));
                    }
                    forms.parse::<Token![:]>()?;
                    variants.push((form.to_string(), forms.parse()?));
                    if forms.peek(Token![,]) {
                        forms.parse::<Token![,]>()?;
                    }
                }
                if !seen.contains("other") {
                    return Err(syn::Error::new_spanned(
                        &key,
                        "plural messages require an other form",
                    ));
                }
            } else {
                variants.push((String::new(), body.parse()?));
            }
            let mut params = std::collections::BTreeMap::new();
            for (_, text) in &variants {
                for name in parameters(text)? {
                    params.insert(name.to_string(), name);
                }
            }
            if plural {
                params.remove("count");
            }
            let message = Message {
                variants,
                parameters: params.into_values().collect(),
                plural,
            };
            if messages.insert(key.to_string(), message).is_some() {
                return Err(syn::Error::new_spanned(key, "duplicate translation key"));
            }
            if body.peek(Token![,]) {
                body.parse::<Token![,]>()?;
            }
        }
        if entries.insert(locale, messages).is_some() {
            return Err(syn::Error::new(span, "duplicate locale"));
        }
    }
    let typed = default.is_some();
    let default = default
        .or(first)
        .ok_or_else(|| input.error("a locale declaration requires at least one locale"))?;
    let baseline = entries
        .get(&default)
        .ok_or_else(|| input.error("default locale must have a catalog"))?;
    for messages in entries.values() {
        for (key, message) in messages {
            let original = baseline.get(key).ok_or_else(|| {
                input.error(format!(
                    "translation key `{key}` is missing from the default locale"
                ))
            })?;
            if message.plural != original.plural || message.parameters != original.parameters {
                return Err(input.error(format!(
                    "translation `{key}` must use the default locale's parameters and plural shape"
                )));
            }
        }
    }
    Ok(CatalogData {
        default,
        typed,
        entries,
    })
}
impl CatalogData {
    fn initializer(&self) -> syn::Expr {
        let default = &self.default;
        let mut messages = Vec::new();
        for (locale, entries) in &self.entries {
            messages.push(quote!(.catalog_locale(#locale)));
            for (key, message) in entries {
                for (form, text) in &message.variants {
                    let key = if message.plural {
                        format!("{key}.{form}")
                    } else {
                        key.clone()
                    };
                    messages.push(quote!(.message(#locale, #key, #text)));
                }
            }
        }
        syn::parse_quote!(::omen_ui::Localizer::new(::omen_ui::Locale::new(#default), #default) #(#messages)*)
    }
}
impl Parse for Catalog {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let visibility = input.parse()?;
        let name = input.parse()?;
        let body;
        braced!(body in input);
        Ok(Self {
            visibility,
            name,
            data: catalog_data(&body)?,
        })
    }
}
pub(crate) fn catalog(input: ParseStream<'_>) -> syn::Result<syn::Expr> {
    Ok(catalog_data(input)?.initializer())
}
pub(crate) fn locale(tokens: TokenStream) -> syn::Result<TokenStream> {
    let Catalog {
        visibility,
        name,
        data,
    } = syn::parse2(tokens)?;
    let initializer = data.initializer();
    let locales = data.entries.keys();
    let constructor = if data.typed {
        quote!(
            pub fn new() -> Self {
                Self::typed()
            }
        )
    } else {
        quote!(#[allow(clippy::new_ret_no_self)] pub fn new() -> ::omen_ui::Localizer { #initializer })
    };
    let methods = data.entries[&data.default].iter().map(|(key, message)| {
        let method: syn::Ident = syn::parse_str(key).expect("validated translation identifier");
        let params = &message.parameters;
        let names = params.iter().map(ToString::to_string).collect::<Vec<_>>();
        let count = message.plural.then(|| quote!(count: i64,));
        let resolve = if message.plural { quote!(self.inner.plural(#key, count, &[#((#names, #params)),*])) }
            else { quote!(self.inner.format(#key, &[#((#names, #params)),*])) };
        quote!(#[doc="Resolve this typed translation in the current locale."] pub fn #method(&self, #count #(#params: &str),*) -> String { #resolve })
    });
    Ok(quote! {
        #[doc="A typed reactive translation resource. Clones share locale selection."]
        #[derive(Clone, Debug)]
        #visibility struct #name { inner: ::omen_ui::Localizer }
        impl #name {
            #[doc="Create independent locale selection using the default catalog."]
            #constructor
            #[doc="Create a typed resource, including for legacy catalogs without default:."]
            pub fn typed() -> Self { Self { inner: #initializer } }
            #[doc="Locales declared by this resource."]
            pub const fn supported_locales() -> &'static [&'static str] { &[#(#locales),*] }
            #[doc="Select a supported locale; unsupported identifiers leave selection unchanged."]
            pub fn try_set_locale(&self, locale: ::omen_ui::Locale) -> Result<(), ::omen_ui::UnsupportedLocale> {
                self.inner.try_set_locale(locale)
            }
            #[doc="Select a supported locale. Unsupported identifiers leave selection unchanged."]
            pub fn set_locale(&self, locale: ::omen_ui::Locale) { let _ = self.try_set_locale(locale); }
            #(#methods)*
        }
        impl ::core::ops::Deref for #name { type Target = ::omen_ui::Localizer; fn deref(&self) -> &Self::Target { &self.inner } }
        impl ::core::default::Default for #name { fn default() -> Self { Self::typed() } }
        impl From<#name> for ::omen_ui::Localizer { fn from(resource: #name) -> Self { resource.inner } }
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use quote::quote;
    #[test]
    fn environment_preserves_resources_and_visibility() {
        let model: Model = syn::parse2(quote! {
            pub AppEnvironment {
                @Reactive pub(crate) title = "Hello"
                receiver: Receiver<()>;
                pub fn method(&self) {}
            }
        })
        .unwrap();
        assert!(model.fields[0].reactive);
        assert!(matches!(
            model.fields[0].visibility,
            syn::Visibility::Restricted(_)
        ));
        assert!(!model.fields[1].reactive);
        assert!(model.fields[1].value.is_none());
        let output = environment(
            quote! { pub AppEnvironment { @Reactive ready = false receiver: Receiver<()>; } },
        )
        .unwrap();
        let _: syn::File = syn::parse2(output).unwrap();
    }
    #[test]
    fn locale_rejects_invalid_catalogs() {
        for (tokens, message) in [
            (
                quote! { Strings { default: "zz" en { title: "Hi" } } },
                "default locale must have a catalog",
            ),
            (
                quote! { Strings { en { title: "Hi" title: "Again" } } },
                "duplicate translation key",
            ),
            (
                quote! { Strings { en { title: "Hi" } en { title: "Again" } } },
                "duplicate locale",
            ),
            (
                quote! { Strings { en { title: "Hi {name}" } ar { title: "Hi {other}" } } },
                "parameters and plural shape",
            ),
            (
                quote! { Strings { en { count: { one: "One" } } } },
                "other form",
            ),
            (
                quote! { Strings { en { title: "Hi" } ar { missing: "Unknown" } } },
                "missing from the default locale",
            ),
            (
                quote! { Strings { "123" { title: "Hi" } } },
                "invalid locale identifier",
            ),
            (
                quote! { Strings { en { title: "Hi {name" } } },
                "unclosed interpolation parameter",
            ),
        ] {
            let error = locale(tokens).unwrap_err().to_string();
            assert!(error.contains(message), "{error}");
        }
    }
}
